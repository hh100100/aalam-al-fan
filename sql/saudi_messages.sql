-- إعداد سجل رسائل الوطن المشترك لموقع عالم الفن الرقمي
-- شغّل هذا الملف مرة واحدة في Supabase SQL Editor للمشروع المرتبط بالموقع.

create table if not exists public.saudi_messages (
  id bigint generated by default as identity primary key,
  participant_type text not null check (participant_type in ('طالب', 'زائر')),
  message text not null check (char_length(trim(message)) between 1 and 180),
  created_at timestamptz not null default now()
);

alter table public.saudi_messages enable row level security;

grant select, insert on public.saudi_messages to anon, authenticated;
grant usage, select on sequence public.saudi_messages_id_seq to anon, authenticated;

drop policy if exists "Anyone can read Saudi messages" on public.saudi_messages;
create policy "Anyone can read Saudi messages"
on public.saudi_messages for select
to anon, authenticated
using (true);

drop policy if exists "Anyone can post Saudi messages" on public.saudi_messages;
create policy "Anyone can post Saudi messages"
on public.saudi_messages for insert
to anon, authenticated
with check (
  participant_type in ('طالب', 'زائر')
  and char_length(trim(message)) between 1 and 180
);
