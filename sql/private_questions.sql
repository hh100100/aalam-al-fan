-- تفعيل استقبال أسئلة الطلاب والطالبات في قسم «اسأل معلمتي»
create table if not exists public.private_questions (
  id bigint generated by default as identity primary key,
  question text not null check (char_length(trim(question)) between 1 and 3000),
  created_at timestamptz not null default now()
);

alter table public.private_questions enable row level security;

grant insert on table public.private_questions to anon, authenticated;
grant usage, select on sequence public.private_questions_id_seq to anon, authenticated;

drop policy if exists "Students can send teacher questions" on public.private_questions;
create policy "Students can send teacher questions"
on public.private_questions
for insert
to anon, authenticated
with check (char_length(trim(question)) between 1 and 3000);

-- لا نمنح الطلاب صلاحية قراءة الأسئلة؛ القراءة تبقى للمعلمة الموثقة فقط.
grant select on table public.private_questions to authenticated;
drop policy if exists "Teacher can read private questions" on public.private_questions;
create policy "Teacher can read private questions"
on public.private_questions
for select
to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'teacher');
